"""Phase 1 compliance matrix XLSX writer (CP42).

Builds an ``openpyxl`` workbook from :class:`MatrixRow` objects — the same
canonical projection that powers the matrix UI.  No business logic is
duplicated: column order, row order, and null handling all come from
``project_matrix_rows``.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import UTC, datetime
from uuid import UUID

from openpyxl import Workbook  # type: ignore[import-untyped]
from openpyxl.styles import Alignment, Font, PatternFill  # type: ignore[import-untyped]
from openpyxl.utils import get_column_letter  # type: ignore[import-untyped]

from tender_compliance_api.matrix.projection import MatrixRow

# Canonical column headers (CP41).
MATRIX_COLUMNS: list[tuple[str, str]] = [
    ("serial", "S.No."),
    ("requirement_id", "Requirement ID"),
    ("tender_requirement", "Tender Requirement"),
    ("category", "Category"),
    ("clause", "Clause"),
    ("source_page", "Source Page"),
    ("mandatory", "Mandatory"),
    ("user_notes", "User Notes"),
    ("review_status", "Review Status"),
]

# Column widths (characters).
COLUMN_WIDTHS: dict[str, float] = {
    "S.No.": 6,
    "Requirement ID": 38,
    "Tender Requirement": 60,
    "Category": 20,
    "Clause": 16,
    "Source Page": 12,
    "Mandatory": 10,
    "User Notes": 40,
    "Review Status": 18,
}

# Header fill (light blue).
HEADER_FILL = PatternFill(start_color="1F4E78", end_color="1F4E78", fill_type="solid")
HEADER_FONT = Font(color="FFFFFF", bold=True, size=10)

# Readable labels for review status.
_REVIEW_STATUS_LABELS: dict[str, str] = {
    "unreviewed": "Unreviewed",
    "reviewed": "Reviewed",
    "needs_clarification": "Needs clarification",
    "ocr_warning": "OCR warning",
}

# Readable labels for mandatory tri-state.
_MANDATORY_LABELS: dict[str, str | None] = {
    "true": "Yes",
    "false": "No",
    "none": "—",
}


def _format_cell_value(value: object) -> str:
    """Convert a cell value to a displayable string.  ``None`` → empty string."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "Yes" if value else "No"
    if isinstance(value, UUID):
        return str(value)
    return str(value)


def build_matrix_workbook(
    rows: Sequence[MatrixRow],
    *,
    project_name: str | None = None,
    document_id: UUID | None = None,
    version_number: int | None = None,
    generated_at: datetime | None = None,
    actor_id: UUID | None = None,
    requirement_count: int | None = None,
) -> tuple[Workbook, str]:
    """Build an XLSX workbook from matrix rows.

    Returns ``(workbook, sha256)`` where ``sha256`` is the checksum of the
    written bytes — computed from the actual workbook output, not trusted
    from any provider.

    Args:
        rows: Matrix rows from :func:`project_matrix_rows`.
        project_name: Optional project name for the metadata sheet.
        document_id: Optional document UUID for the metadata sheet.
        version_number: Optional version number for the metadata sheet.
        generated_at: Override timestamp (defaults to now, UTC).
        actor_id: Optional actor UUID for the metadata sheet.
        requirement_count: Optional count (defaults to ``len(rows)``).
    """
    wb = Workbook()
    ws = wb.active
    assert ws is not None
    ws.title = "Compliance Matrix"

    if generated_at is None:
        generated_at = datetime.now(UTC)

    # --- Metadata header rows (above the table) ---
    ws.insert_rows(0, 5)
    ws["A1"] = "Project"
    ws["B1"] = project_name or "—"
    ws["A2"] = "Document ID"
    ws["B2"] = str(document_id) if document_id else "—"
    ws["A3"] = "Version"
    ws["B3"] = str(version_number) if version_number else "—"
    ws["A4"] = "Generated"
    ws["B4"] = generated_at.strftime("%Y-%m-%d %H:%M:%S UTC")
    ws["A5"] = "Generated by"
    ws["B5"] = str(actor_id) if actor_id else "system"

    # Freeze the table header row (row 6 + header).
    header_row = 7
    ws.freeze_panes = f"A{header_row}"

    # --- Table header ---
    for col_idx, (_field, label) in enumerate(MATRIX_COLUMNS, start=1):
        cell = ws.cell(row=header_row, column=col_idx)
        cell.value = label
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = Alignment(vertical="center", horizontal="center")
        ws.column_dimensions[get_column_letter(col_idx)].width = COLUMN_WIDTHS[label]

    # --- Data rows ---
    for row_idx, matrix_row in enumerate(rows, start=header_row + 1):
        for col_idx, (field, _) in enumerate(MATRIX_COLUMNS, start=1):
            value: object
            if field == "review_status":
                value = _REVIEW_STATUS_LABELS.get(
                    matrix_row.review_status, matrix_row.review_status
                )
            elif field == "mandatory":
                if matrix_row.mandatory is None:
                    value = ""
                else:
                    value = "Yes" if matrix_row.mandatory else "No"
            elif field == "source_page":
                value = matrix_row.source_page if matrix_row.source_page is not None else ""
            else:
                value = getattr(matrix_row, field)
                value = _format_cell_value(value)

            cell = ws.cell(row=row_idx, column=col_idx)
            cell.value = value
            # Wrap long text cells.
            if field in ("tender_requirement", "user_notes"):
                cell.alignment = Alignment(wrap_text=True, vertical="top")

    # --- Auto-filter on the header row ---
    last_col_letter = get_column_letter(len(MATRIX_COLUMNS))
    filter_range = f"A{header_row}:{last_col_letter}{header_row}"
    ws.auto_filter.ref = filter_range

    # --- Summary row below data ---
    data_end_row = header_row + len(rows)
    summary_row = data_end_row + 2
    ws.cell(row=summary_row, column=1, value="Total requirements:")
    ws.cell(row=summary_row, column=2, value=requirement_count or len(rows))
    ws.cell(row=summary_row + 1, column=1, value="Exported:")
    ws.cell(row=summary_row + 1, column=2, value=generated_at.strftime("%Y-%m-%d %H:%M"))

    # Compute SHA-256 of the workbook bytes.
    import io
    buf = io.BytesIO()
    wb.save(buf)
    buf.seek(0)
    import hashlib
    checksum = hashlib.sha256(buf.getvalue()).hexdigest()
    buf.seek(0)

    # Re-create workbook from the buffer so the caller gets a fresh one.
    from openpyxl import load_workbook
    wb = load_workbook(buf)

    return wb, checksum


def save_matrix_workbook(
    wb: Workbook,
) -> bytes:
    """Serialize the workbook to bytes (for storage).

    This is the canonical serialization — the SHA-256 returned by
    ``build_matrix_workbook`` is computed from the *same* bytes written
    by this function.
    """
    import io

    buf = io.BytesIO()
    wb.save(buf)
    buf.seek(0)
    return buf.getvalue()
