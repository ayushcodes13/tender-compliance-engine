"""Final compliance matrix PDF writer (CP60).

Generates a PDF deliverable from the canonical ``FinalMatrixRow`` projection
(CP59) using PyMuPDF (``pymupdf``).  Presentation only — never recomputes or
invents compliance facts (CP60 guardrail).
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import UTC, datetime
from decimal import Decimal
from io import BytesIO
from uuid import UUID

import pymupdf

from tender_compliance_api.matrix.projection import FinalMatrixRow

# Page geometry (points; 1 inch = 72 pt, A4 = 595 × 842).
_PAGE_W = 595
_PAGE_H = 842
_MARGIN = 40.0
_HEADER_H = 36
_FOOTER_H = 12
_ROW_H = 14
_HEADER_ROW_Y = _PAGE_H - _MARGIN - _HEADER_H

_ASSESSMENT_STATUS_LABELS: dict[str, str] = {
    "compliant": "Compliant",
    "non_compliant": "Non-Compliant",
    "partial": "Partial",
    "not_demonstrated": "Not Demonstrated",
    "conflict": "Conflict",
    "human_review_required": "Human Review Required",
}

# Column definitions: (field_name, header, width_pts)
_COLUMNS: list[tuple[str, str, float]] = [
    ("serial", "S.No.", 30),
    ("requirement_id", "Req ID", 100),
    ("tender_requirement", "Tender Requirement", 120),
    ("assessment_status", "Assessment", 70),
    ("vendor_spec_value", "V.Value", 45),
    ("vendor_spec_unit", "V.Unit", 40),
    ("evidence_id", "Evidence ID", 100),
    ("assessment_is_confirmed", "Confirmed", 50),
    ("has_unresolved_conflict", "Conflict", 50),
]


def _fmt(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "Y" if value else "N"
    if isinstance(value, Decimal):
        return str(float(value))
    if isinstance(value, UUID):
        return str(value)[:8]
    if isinstance(value, float):
        return str(value)
    return str(value)


def _assess_label(status: str | None) -> str:
    if status is None:
        return ""
    return _ASSESSMENT_STATUS_LABELS.get(status, status)


def _row_text(row: FinalMatrixRow) -> list[str]:
    """Format the display text for each column of a matrix row."""
    status = row.assessment_status
    if status is None and row.assessment_suggested_status is not None:
        status = row.assessment_suggested_status
    return [
        _fmt(row.serial),
        _fmt(row.requirement_id)[:8],
        _truncate(_fmt(row.tender_requirement), 80),
        _assess_label(status),
        _fmt(row.vendor_spec_value),
        _fmt(row.vendor_spec_unit),
        _fmt(row.evidence_id)[:8],
        "Y" if row.assessment_is_confirmed else (
            "N" if row.assessment_is_confirmed is not None else ""
        ),
        "Y" if row.has_unresolved_conflict else "N",
    ]


def _truncate(text: str, max_len: int) -> str:
    if len(text) <= max_len:
        return text
    return text[: max_len - 3] + "..."


def build_final_matrix_pdf(
    rows: Sequence[FinalMatrixRow],
    *,
    project_name: str | None = None,
    document_id: UUID | None = None,
    version_number: int | None = None,
    generated_at: datetime | None = None,
    actor_id: UUID | None = None,
    requirement_count: int | None = None,
) -> bytes:
    """Build a PDF deliverable from final matrix rows (CP59/CP60).

    Returns the document as ``bytes``.
    """
    if generated_at is None:
        generated_at = datetime.now(UTC)

    doc = pymupdf.open()  # type: ignore[no-untyped-call]

    # --- Compute column x positions ---
    x_positions: list[float] = []
    x = _MARGIN
    for _, _, width in _COLUMNS:
        x_positions.append(x)
        x += width

    # --- Title page ---
    page = doc.new_page(width=_PAGE_W, height=_PAGE_H)
    page.insert_text(
        (_PAGE_W / 2, 120), "Final Compliance Matrix",
        fontsize=18, fontname="helv",
    )
    meta_y = 180
    for label, val in (
        ("Project", project_name or "—"),
        ("Document ID", str(document_id) if document_id else "—"),
        ("Version", str(version_number) if version_number else "—"),
        ("Generated", generated_at.strftime("%Y-%m-%d %H:%M UTC")),
        ("Generated by", str(actor_id) if actor_id else "system"),
        ("Total requirements", str(requirement_count or len(rows))),
    ):
        page.insert_text((_MARGIN, meta_y), f"{label}: {val}", fontsize=9)
        meta_y += 16

    # --- Data pages ---
    data_rect_top = _MARGIN
    data_rect_bottom = _PAGE_H - _MARGIN - _FOOTER_H
    available_height = data_rect_bottom - data_rect_top - _HEADER_H
    rows_per_page = int(available_height // _ROW_H)

    total_rows = len(rows)
    if total_rows == 0:
        page = doc.new_page(width=_PAGE_W, height=_PAGE_H)
        page.insert_text(
            (_PAGE_W / 2, _PAGE_H / 2),
            "No requirements in this document version.",
            fontsize=12, fontname="helv",
        )
    else:
        start = 0
        page_num = 0
        while start < total_rows:
            page_num += 1
            page = doc.new_page(width=_PAGE_W, height=_PAGE_H)

            # Header row
            y = _HEADER_ROW_Y
            for col_idx, (_, header, _) in enumerate(_COLUMNS):
                page.insert_text(
                    (x_positions[col_idx], y),
                    header, fontsize=7, fontname="hebo",
                )
            y += _ROW_H

            # Separator line
            page.draw_line(
                pymupdf.Point(_MARGIN, y),  # type: ignore[no-untyped-call]
                pymupdf.Point(_PAGE_W - _MARGIN, y),  # type: ignore[no-untyped-call]
            )
            y += 2

            end = min(start + rows_per_page, total_rows)
            for i in range(start, end):
                row = rows[i]
                texts = _row_text(row)
                for col_idx, text in enumerate(texts):
                    page.insert_text(
                        (x_positions[col_idx], y),
                        text, fontsize=6.5, fontname="helv",
                    )
                y += _ROW_H

                # Page break check
                if y > data_rect_bottom - _ROW_H:
                    break

            # If we broke early due to space, continue on next page
            if y > data_rect_bottom - _ROW_H:
                start = i + 1
            else:
                start = end
                # This page is done; advance to next batch
                if start >= total_rows:
                    break

            # Footer
            footer_y = _PAGE_H - _MARGIN
            page.insert_text(
                (_MARGIN, footer_y),
                f"Page {page_num}  |  Generated: {generated_at.strftime('%Y-%m-%d %H:%M:%S UTC')}",
                fontsize=7, fontname="helv",
            )

    buf = BytesIO()
    doc.save(buf)  # type: ignore[no-untyped-call]
    doc.close()  # type: ignore[no-untyped-call]
    return buf.getvalue()
