"""Final compliance matrix DOCX writer (CP60).

Generates a Word ``.docx`` deliverable from the canonical
``FinalMatrixRow`` projection (CP59).  Presentation only — never recomputes
or invents compliance facts (CP60 guardrail).
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import UTC, datetime
from decimal import Decimal
from io import BytesIO
from uuid import UUID

import docx
from docx.shared import Pt

from tender_compliance_api.matrix.projection import FinalMatrixRow

_ASSESSMENT_STATUS_LABELS: dict[str, str] = {
    "compliant": "Compliant",
    "non_compliant": "Non-Compliant",
    "partial": "Partial",
    "not_demonstrated": "Not Demonstrated",
    "conflict": "Conflict",
    "human_review_required": "Human Review Required",
}


def _format_value(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "Yes" if value else "No"
    if isinstance(value, Decimal):
        return str(float(value))
    if isinstance(value, UUID):
        return str(value)
    if isinstance(value, datetime):
        return value.strftime("%Y-%m-%d %H:%M UTC")
    if isinstance(value, list):
        return "; ".join(str(v) for v in value)
    return str(value)


def build_final_matrix_docx(
    rows: Sequence[FinalMatrixRow],
    *,
    project_name: str | None = None,
    document_id: UUID | None = None,
    version_number: int | None = None,
    generated_at: datetime | None = None,
    actor_id: UUID | None = None,
    requirement_count: int | None = None,
) -> bytes:
    """Build a DOCX deliverable from final matrix rows (CP59/CP60).

    Returns the document as ``bytes``.
    """
    if generated_at is None:
        generated_at = datetime.now(UTC)

    doc = docx.Document()

    # --- Title ---
    doc.add_heading("Final Compliance Matrix", level=0)

    # --- Metadata ---
    for label, val in (
        ("Project", project_name or "—"),
        ("Document ID", str(document_id) if document_id else "—"),
        ("Version", str(version_number) if version_number else "—"),
        ("Generated", generated_at.strftime("%Y-%m-%d %H:%M:%S UTC")),
        ("Generated by", str(actor_id) if actor_id else "system"),
    ):
        p = doc.add_paragraph()
        p.add_run(f"{label}: ").bold = True
        p.add_run(val)
    doc.add_paragraph()

    # --- Summary ---
    doc.add_paragraph(
        f"Total requirements: {requirement_count or len(rows)}",
        style="List Bullet",
    )
    doc.add_paragraph()

    # --- Detail table ---
    # Columns: S.No., Requirement ID, Tender Requirement, Assessment Status,
    # Vendor Spec (Value/Unit), Evidence, Conflict, Clarifications, Deviations.
    headers = [
        "S.No.", "Requirement ID", "Tender Requirement",
        "Assessment Status", "Vendor Spec", "Evidence ID",
        "Evidence Score", "Confirmed", "Conflict",
        "Clarifications", "Deviations",
    ]
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    hdr = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = h
        for para in hdr[i].paragraphs:
            for run in para.runs:
                run.bold = True
                run.font.size = Pt(9)

    for row in rows:
        cells = table.add_row().cells
        cells[0].text = _format_value(row.serial)
        cells[1].text = _format_value(row.requirement_id)
        cells[2].text = _truncate(row.tender_requirement)
        status = row.assessment_status or ""
        if status:
            status = _ASSESSMENT_STATUS_LABELS.get(status, status)
        cells[3].text = status
        vspec = (
            f"{_format_value(row.vendor_spec_value)} "
            f"{_format_value(row.vendor_spec_unit)}"
        ).strip()
        cells[4].text = vspec
        cells[5].text = _format_value(row.evidence_id)
        cells[6].text = _format_value(row.evidence_score)
        confirmed = "Yes" if row.assessment_is_confirmed else (
            "No" if row.assessment_is_confirmed is not None else ""
        )
        cells[7].text = confirmed
        cells[8].text = "Yes" if row.has_unresolved_conflict else "No"
        cells[9].text = "; ".join(row.clarification_statuses) if row.clarification_statuses else ""
        cells[10].text = "; ".join(row.deviation_statuses) if row.deviation_statuses else ""
        for cell in cells:
            for para in cell.paragraphs:
                for run in para.runs:
                    run.font.size = Pt(8)

    buf = BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _truncate(text: str, max_len: int = 200) -> str:
    if text is None:
        return ""
    if len(text) > max_len:
        return text[: max_len - 3] + "..."
    return text
